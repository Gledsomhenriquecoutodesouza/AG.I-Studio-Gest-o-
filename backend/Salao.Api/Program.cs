   var user=await db.SalonUsers.AsNoTracking().SingleOrDefaultAsync(x=>x.Id==userId&&x.Active);
   if(user is not null&&SalonUserSessions.IsValid(user,token))context.Items["SalonUser"]=user;
   else {context.Response.StatusCode=401;context.Response.Headers["X-Session-Expired"]="true";await context.Response.WriteAsJsonAsync(new{message="Sessão expirada. Entre novamente."});return;}
